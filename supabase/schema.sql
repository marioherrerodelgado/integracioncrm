-- Solicitudes de los formularios de la web.
-- El Worker (/api/contacto) inserta con la clave service_role, que se salta RLS.
-- El panel interno (integracionCRM-panel) lee y actualiza con la sesión de la
-- persona, y solo si su email está en panel_usuarios.
-- Se puede ejecutar varias veces sin romper nada.

create table if not exists public.contactos (
  id bigint generated by default as identity primary key,
  creado_en timestamptz not null default now(),
  tipo text,
  nombre text not null,
  email text not null,
  telefono text,
  empresa text,
  crm text,
  objetivo text,
  plataforma text,
  fecha text,
  hora text
);

-- Seguimiento comercial desde el panel
alter table public.contactos
  add column if not exists estado text not null default 'nuevo'
    check (estado in ('nuevo', 'contactado', 'cualificado', 'descartado')),
  add column if not exists puntuacion int not null default 50
    check (puntuacion between 0 and 100),
  add column if not exists responsable text,
  add column if not exists origen text not null default 'Web';

alter table public.contactos enable row level security;

-- Quién puede entrar al panel
create table if not exists public.panel_usuarios (
  email text primary key
);
alter table public.panel_usuarios enable row level security;

