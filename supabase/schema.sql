create or replace function public.es_usuario_panel()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.panel_usuarios
    where email = lower(auth.jwt() ->> 'email')
  );
$$;

drop policy if exists "panel lee contactos" on public.contactos;
create policy "panel lee contactos" on public.contactos
  for select to authenticated using (public.es_usuario_panel());

drop policy if exists "panel crea contactos" on public.contactos;
create policy "panel crea contactos" on public.contactos
  for insert to authenticated with check (public.es_usuario_panel());

drop policy if exists "panel actualiza contactos" on public.contactos;
create policy "panel actualiza contactos" on public.contactos
  for update to authenticated using (public.es_usuario_panel()) with check (public.es_usuario_panel());
